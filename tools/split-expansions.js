// Splits the monolithic expansions.js (~2 MB) into per-course slices in
// /expansions/<courseId>.js so the frontend can lazy-load just the course
// the user is opening, instead of shipping every course on first paint.
//
// Run after tools/expand-quizzes.js whenever expansions.js is regenerated:
//   node tools/split-expansions.js
//
// The output files are committed and served by server.js as static assets.

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'expansions.js');
const OUT_DIR = path.join(ROOT, 'expansions');

if (!fs.existsSync(SRC)) {
  console.error('expansions.js not found at', SRC);
  process.exit(1);
}

const lines = fs.readFileSync(SRC, 'utf8').split(/\r?\n/);
const buckets = {};
const callRe = /^\s*(add|addCum)\(\s*"([^"]+)"/;
let calls = 0;

for (const ln of lines) {
  const m = ln.match(callRe);
  if (!m) continue;
  const id = m[2];
  (buckets[id] ||= []).push(ln);
  calls++;
}

if (calls === 0) {
  console.error('No add()/addCum() calls found. Did expansions.js change format?');
  process.exit(1);
}

if (!fs.existsSync(OUT_DIR)) fs.mkdirSync(OUT_DIR);

const HEADER = `// AUTO-GENERATED by tools/split-expansions.js — do not edit by hand.
// Per-course slice of expansions.js. Loaded on demand when the user opens this course.

(function() {
  if (typeof COURSES === "undefined") { console.error("course expansion: COURSES not loaded"); return; }
  function add(courseId, bookId, sIdx, qs) {
    const c = COURSES[courseId]; if (!c) return;
    const b = c.books.find(x => x.id === bookId); if (!b) return;
    const s = b.sections[sIdx]; if (!s) return;
    s.questions.push(...qs);
  }
  function addCum(courseId, bookId, qs) {
    const c = COURSES[courseId]; if (!c) return;
    const b = c.books.find(x => x.id === bookId); if (!b || !b.cumulativeTest) return;
    b.cumulativeTest.questions.push(...qs);
  }

`;
const FOOTER = `})();
`;

const ids = Object.keys(buckets).sort();
let totalWritten = 0;
for (const id of ids) {
  const body = buckets[id].join('\n') + '\n';
  const out = HEADER + body + FOOTER;
  const dest = path.join(OUT_DIR, `${id}.js`);
  fs.writeFileSync(dest, out);
  totalWritten += buckets[id].length;
  console.log(`  expansions/${id}.js  (${buckets[id].length} calls, ${(out.length / 1024).toFixed(0)} KB)`);
}

console.log(`\nsplit ${totalWritten}/${calls} calls into ${ids.length} per-course files.`);
if (totalWritten !== calls) {
  console.error('Mismatch — some calls were lost. Aborting before commit.');
  process.exit(1);
}
